def supported_math(txt):
    # Arial lacks some Unicode sub/superscript glyphs; render real PDF scripts.
    sup=str.maketrans('⁻⁰¹²³⁴⁵⁶⁷⁸⁹','-0123456789')
    sub=str.maketrans('₀₁₂₃₄₅₆₇₈₉','0123456789')
    txt=re.sub('[⁻⁰¹²³⁴⁵⁶⁷⁸⁹]+',lambda m:'<super>'+m[0].translate(sup)+'</super>',txt)
    txt=re.sub('[₀₁₂₃₄₅₆₇₈₉]+',lambda m:'<sub>'+m[0].translate(sub)+'</sub>',txt)
    return txt.replace('–','-').replace('—','-').replace('−','-')
